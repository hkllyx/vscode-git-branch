'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { GitOperations } = require('../src/git-operations');

test('Update fetches upstream, fast-forwards local branches without switching, and protects commits/worktrees/files', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'gb-update-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const writerPath = path.join(root, 'writer');
  await fs.mkdir(writerPath);
  const writer = new GitOperations(writerPath);
  await writer.exec(['init', '-b', 'main']);
  await writer.exec(['config', 'user.name', 'Test']);
  await writer.exec(['config', 'user.email', 'test@example.invalid']);
  await fs.writeFile(path.join(writerPath, 'file.txt'), 'base');
  await writer.exec(['add', '.']); await writer.exec(['commit', '-m', 'base']);
  const base = await writer.resolve('HEAD');
  const serverPath = path.join(root, 'server.git');
  await writer.exec(['clone', '--bare', writerPath, serverPath]);
  await writer.exec(['remote', 'add', 'origin', serverPath]);
  const localPath = path.join(root, 'local');
  await writer.exec(['clone', serverPath, localPath]);
  const git = new GitOperations(localPath);
  await git.exec(['config', 'user.name', 'Test']);
  await git.exec(['config', 'user.email', 'test@example.invalid']);
  const node = (ref, remote = false) => ({ kind: 'branch', ref, remote, label: ref });
  for (const name of ['other', 'diverged', 'occupied']) await git.create(name, 'refs/remotes/origin/main');
  await git.create('no-tracking', base);
  await git.checkout({ ref: 'diverged' });
  await fs.writeFile(path.join(localPath, 'local.txt'), 'local-only');
  await git.exec(['add', '.']); await git.exec(['commit', '-m', 'local-only']);
  const divergedHash = await git.resolve('HEAD');
  await git.checkout({ ref: 'main' });
  const otherWorktree = path.join(root, 'occupied-worktree');
  await git.exec(['worktree', 'add', otherWorktree, 'occupied']);
  const publish = async text => {
    await fs.writeFile(path.join(writerPath, 'file.txt'), text);
    await writer.exec(['add', '.']); await writer.exec(['commit', '-m', text]);
    await writer.exec(['push', 'origin', 'main']);
    return writer.resolve('HEAD');
  };
  const next = await publish('remote-new');
  await fs.writeFile(path.join(localPath, 'file.txt'), 'dirty-main');
  const index = await git.exec(['diff', '--cached']);
  assert.equal(await git.update(node('other')), 'Updated (fast-forward)');
  assert.equal(await git.resolve('refs/heads/other'), next);
  assert.equal(await git.current(), 'main');
  assert.equal(await git.resolve('HEAD'), base);
  assert.equal(await fs.readFile(path.join(localPath, 'file.txt'), 'utf8'), 'dirty-main');
  assert.equal(await git.exec(['diff', '--cached']), index);
  await assert.rejects(git.update(node('main')), /working tree changes/);
  assert.equal(await git.resolve('HEAD'), base);
  await git.exec(['restore', '--', 'file.txt']);
  await assert.rejects(git.update(node('main'), true), /working tree changes/);
  const mergeHead = path.join(localPath, '.git', 'MERGE_HEAD');
  await fs.writeFile(mergeHead, `${base}\n`);
  await assert.rejects(git.update(node('main')), /in progress/);
  assert.equal(await git.resolve('HEAD'), base);
  await fs.unlink(mergeHead);
  assert.equal(await git.update(node('main')), 'Updated (fast-forward)');
  assert.equal(await git.resolve('HEAD'), next);
  assert.equal(await fs.readFile(path.join(localPath, 'file.txt'), 'utf8'), 'remote-new');
  await assert.rejects(git.update(node('diverged')), /diverged/);
  assert.equal(await git.resolve('refs/heads/diverged'), divergedHash);
  await assert.rejects(git.update(node('occupied')), /checked out/i);
  assert.equal(await git.resolve('refs/heads/occupied'), base);
  assert.equal(await fs.readFile(path.join(otherWorktree, 'file.txt'), 'utf8'), 'base');
  await assert.rejects(git.update(node('no-tracking')), /No tracking/);
  await git.exec(['commit', '--allow-empty', '-m', 'ahead-only']);
  const ahead = await git.resolve('HEAD');
  assert.equal(await git.update(node('main')), 'Already up to date');
  assert.equal(await git.resolve('HEAD'), ahead);
  const newest = await publish('remote-newer');
  assert.equal(await git.update(node('origin/main', true)), 'Fetched');
  assert.equal(await git.resolve('refs/remotes/origin/main'), newest);
  assert.equal(await git.resolve('HEAD'), ahead);
  await assert.rejects(git.update(node('main')), /diverged/);
  assert.equal(await git.resolve('HEAD'), ahead);
  // Local upstream: no network fetch, same fast-forward behavior.
  await git.create('local-upstream', base);
  await git.setTracking('local-upstream', 'refs/heads/other');
  assert.equal(await git.update(node('local-upstream')), 'Updated (fast-forward)');
  assert.equal(await git.resolve('refs/heads/local-upstream'), next);
  await git.exec(['remote', 'set-url', 'origin', path.join(root, 'does-not-exist.git')]);
  await assert.rejects(git.update(node('other')));
  assert.equal(await git.resolve('refs/heads/other'), next);
  assert.equal(await git.resolve('HEAD'), ahead);
  await assert.rejects(git.update({ ...node('other'), diffSession: true }), /Select a branch/);
  assert.equal(await git.exec(['status', '--porcelain']), '');
});
