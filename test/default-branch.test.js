'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { GitOperations } = require('../src/git-operations');

test('default branch differs from current: remote HEAD wins, name fallback is deterministic', async t => {
  const cwd = await fs.mkdtemp(path.join(os.tmpdir(), 'git-branch-primary-'));
  t.after(() => fs.rm(cwd, { recursive: true, force: true }));
  const git = new GitOperations(cwd);
  await git.exec(['init', '-b', 'main']);
  await git.exec(['config', 'user.name', 'Test']); await git.exec(['config', 'user.email', 'test@example.invalid']);
  await git.exec(['commit', '--allow-empty', '-m', 'initial']);
  await git.create('master'); await git.create('trunk'); await git.create('feature');
  await git.checkout({ ref: 'feature' });
  let result = await git.branches();
  assert.deepEqual(result.branches.filter(b => b.primary).map(b => b.name), ['main']);
  assert.deepEqual(result.branches.filter(b => b.current).map(b => b.name), ['feature']);
  const hash = await git.resolve('HEAD');
  for (const ref of ['origin/main', 'origin/trunk', 'upstream/master']) await git.exec(['update-ref', `refs/remotes/${ref}`, hash]);
  await git.exec(['symbolic-ref', 'refs/remotes/origin/HEAD', 'refs/remotes/origin/trunk']);
  await git.exec(['symbolic-ref', 'refs/remotes/upstream/HEAD', 'refs/remotes/upstream/master']);
  result = await git.branches();
  assert.deepEqual(result.branches.filter(b => b.primary).map(b => b.name).sort(), ['origin/trunk', 'trunk', 'upstream/master']);
  assert.ok(!result.branches.some(b => b.name.endsWith('/HEAD')));
  await git.checkout({ ref: 'trunk' });
  assert.ok((await git.branches()).branches.find(b => b.name === 'trunk').current);
  await git.exec(['checkout', '--detach', hash]);
  assert.ok(!(await git.branches()).branches.some(b => b.current));
  await git.exec(['symbolic-ref', '--delete', 'refs/remotes/origin/HEAD']);
  result = await git.branches();
  assert.ok(result.branches.find(b => b.name === 'main').primary);
  assert.ok(result.branches.find(b => b.name === 'origin/main').primary);
  assert.ok(!result.branches.find(b => b.name === 'origin/trunk').primary);
});
